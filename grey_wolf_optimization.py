import random


routes = [10, 8, 12, 6, 9]


wolves = routes.copy()

iterations = 20

for t in range(iterations):

    a = 2 - (2 * t / iterations)


    wolves.sort()


    alpha = wolves[0]
    beta = wolves[1]
    delta = wolves[2]

    new_wolves = []

    for X in wolves:

        positions = []

        for leader in [alpha, beta, delta]:

            A = 2 * a * random.random() - a
            C = 2 * random.random()

            D = abs(C * leader - X)

            new_position = leader - A * D

            positions.append(new_position)

        updated_position = sum(positions) / 3

        best_route = min(routes,
                         key=lambda r: abs(r - updated_position))

        new_wolves.append(best_route)

    wolves = new_wolves


best_route = min(wolves)

print("Available routes:", routes)
print("Best route to school:", best_route, "km")