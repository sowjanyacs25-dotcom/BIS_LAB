import numpy as np
import random

cities = np.array([[0, 0], [1, 5], [5, 2], [6, 6]])
n = len(cities)
d = np.linalg.norm(cities[:, None] - cities, axis=2)
p = np.ones((n, n))
best, best_dist = None, float('inf')

for _ in range(100):
    for _ in range(10):
        route = [random.randrange(n)]
        while len(route) < n:
            i = route[-1]
            c = [j for j in range(n) if j not in route]
            w = [p[i,j] / (d[i,j]**2 + 1e-9) for j in c]
            route.append(random.choices(c, weights=w)[0])

        length = sum(d[route[i], route[(i+1)%n]] for i in range(n))
        if length < best_dist:
            best, best_dist = route[:], length
        for i in range(n):
            a, b = route[i], route[(i+1)%n]
            p[a,b] += 1 / length
    p *= 0.5

print("Best Route:", best + [best[0]])
print("Shortest Distance:", round(best_dist, 2))