import random


GRID_SIZE = 10
ITERATIONS = 100

distance = {
    (0, 1): 5,
    (1, 2): 4,
    (2, 3): 6,
    (0, 2): 3,
    (2, 1): 2,
    (1, 3): 5
}


routes = [
    [0, 1, 2, 3],
    [0, 2, 1, 3],
    [0, 1, 3, 2]
]


def total_distance(route):
    D = 0

    for i in range(len(route) - 1):
        a = route[i]
        b = route[i + 1]

        # Formula: D = d1 + d2 + ... + dn
        D += distance.get((a, b),
                          distance.get((b, a), 10))

    return D



def fitness(route):

    # Formula: Fitness(R) = D(R)
    return total_distance(route)


grid = [
    [random.choice(routes) for j in range(GRID_SIZE)]
    for i in range(GRID_SIZE)
]

for iteration in range(ITERATIONS):

    new_grid = []

    for i in range(GRID_SIZE):
        new_row = []

        for j in range(GRID_SIZE):

            neighbors = []

            for a in range(max(0, i-1),
                           min(GRID_SIZE, i+2)):
                for b in range(max(0, j-1),
                               min(GRID_SIZE, j+2)):
                    neighbors.append(grid[a][b])

            best_route = min(neighbors, key=fitness)

            new_row.append(best_route)

        new_grid.append(new_row)

    grid = new_grid



all_routes = [route for row in grid for route in row]

best_route = min(all_routes, key=fitness)


print("Best Delivery Route:", best_route)
print("Minimum Distance:", fitness(best_route), "km")
print("Total Iterations:", ITERATIONS)